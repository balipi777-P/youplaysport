const LangContext = createContext({ lang: 'fr', setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState('fr');

  useEffect(() => {
    try {
      const stored = localStorage.getItem('yps_lang');
      if (stored === 'fr' || stored === 'en') setLangState(stored);
    } catch { /* ignore */ }
  }, []);

  useEffect(() => {
    try { document.documentElement.lang = lang; } catch { /* ignore */ }
  }, [lang]);

  const setLang = useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem('yps_lang', l); } catch { /* ignore */ }
  }, []);

  const t = useCallback((key, vars) => {
    let s = (DICT[lang] && DICT[lang][key]) ?? (DICT.fr[key] ?? key);
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k]);
    return s;
  }, [lang]);

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export function useT() {
  return useContext(LangContext);
}

/** Petit sélecteur FR | EN à poser en haut de page. */
export function LangToggle({ style, big = false }) {
  const { lang, setLang } = useT();
  const base = {
    border: 'none', borderRadius: 8, padding: big ? '0 12px' : '4px 9px', ...(big ? { minWidth: 44, minHeight: 44 } : {}), fontSize: 12, fontWeight: 800,
    cursor: 'pointer', fontFamily: 'inherit', letterSpacing: '.3px',
  };
  return (
    <div style={{ display: 'inline-flex', gap: 3, background: '#F1E9E1', borderRadius: 10, padding: 3, ...style }}>
      {['fr', 'en'].map((l) => (
        <button key={l} type="button" onClick={() => setLang(l)}
          style={{ ...base, background: lang === l ? 'var(--brand)' : 'transparent', color: lang === l ? '#fff' : '#6B665A' }}>
          {l.toUpperCase()}
        </button>
      ))}
    </div>
  );
}
